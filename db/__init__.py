"""The JSE persistence layer, split out of the former 9,191-line database_manager.

Import `database_manager` rather than this package: it is the stable facade that
every caller already uses, and it forwards the mutable connection state that
tests repoint at a throwaway database.

Modules are layered — each may import only from the layers above it:

    connection   paths, WAL, retry, the keepalive pin
    constants    vocabularies, thresholds, term lists
    text         pure normalisation and key derivation
    companies    advertiser-versus-employer classification
    settings     app settings, credentials, lane preferences
    scrapers     plugin registry, health, repairs
    lanes        profiles, people, candidate memory, lane terms
    outcomes     the funnel loop, priors, targeting, channel warmth
    jobs         job records, dedupe, pipeline stages, kits, interviews
    campaign     campaign scoring, the daily plan, attack queue
    intel        hidden market, leads, warm contacts
    dashboard    aggregate views

The domain is genuinely cyclic in a few places (a job transition writes an
outcome; an outcome snapshot reads the job). Those crossings use a function-local
import at the call site, marked with a comment, rather than a module-level one.
"""
